/**
 * A throwaway git repo to point the real workspace/merger at.
 *
 * It is deliberately tiny: the load test is about event volume, worktree churn and the merge queue,
 * not about scanning a big tree. `scripts.test` is `true`, so the real auditor and the real merger
 * both execute a genuine (but instant) test command in the worktrees they own.
 */
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { exec } from '../../packages/core/src/index.ts';

export interface GeneratedRepo {
  /** Temporary parent: repo, worktrees and the SQLite database all live under it. */
  root: string;
  repo: string;
  worktreeRoot: string;
  dbPath: string;
  /** Remove the whole temp tree. Safe to call twice. */
  cleanup(): Promise<void>;
}

const PACKAGE_JSON = `${JSON.stringify(
  {
    name: 'starling-load-target',
    private: true,
    type: 'module',
    scripts: { test: 'true' },
  },
  null,
  2,
)}\n`;

const MAIN_TS = `/** Load-test target: no framework, no dependencies. */
export function greet(name: string): string {
  return \`hello \${name}\`;
}
`;

const README = `# starling-load-target

Generated by \`tools/load\` (Epic 70). Never committed: the whole tree is temporary.
`;

async function git(cwd: string, args: string[]): Promise<void> {
  const result = await exec(['git', ...args], {
    cwd,
    timeoutMs: 30_000,
    env: {
      // Local identity only; the developer's global git config is never touched.
      GIT_AUTHOR_NAME: 'Starling Load',
      GIT_AUTHOR_EMAIL: 'load@starling.local',
      GIT_COMMITTER_NAME: 'Starling Load',
      GIT_COMMITTER_EMAIL: 'load@starling.local',
    },
  });
  if (result.code !== 0) {
    throw new Error(`git ${args.join(' ')} failed in ${cwd}: ${result.stderr || result.stdout}`);
  }
}

/** Create `<temp>/repo` on `main` with one commit, plus an empty worktree root beside it. */
export async function createGeneratedRepo(): Promise<GeneratedRepo> {
  const root = await mkdtemp(join(tmpdir(), 'starling-load-'));
  const repo = join(root, 'repo');
  const worktreeRoot = join(root, 'worktrees');
  const dbPath = join(root, 'load.db');

  await mkdir(join(repo, 'src'), { recursive: true });
  await mkdir(worktreeRoot, { recursive: true });
  await writeFile(join(repo, 'package.json'), PACKAGE_JSON, 'utf8');
  await writeFile(join(repo, 'src', 'main.ts'), MAIN_TS, 'utf8');
  await writeFile(join(repo, 'README.md'), README, 'utf8');

  await git(repo, ['init', '-q', '-b', 'main']);
  await git(repo, ['add', '-A']);
  await git(repo, ['commit', '-q', '-m', 'chore: generated load-test repo']);

  let cleaned = false;
  return {
    root,
    repo,
    worktreeRoot,
    dbPath,
    async cleanup() {
      if (cleaned) return;
      cleaned = true;
      // Worktrees hold git locks; `git worktree prune` is unnecessary once the tree is gone.
      await rm(root, { recursive: true, force: true });
    },
  };
}

/** The generated repo's test command, mirrored from its package.json. */
export const GENERATED_TEST_COMMAND = 'bun run test';
