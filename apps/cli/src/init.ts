import { existsSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { CONFIG_FILENAMES, defaultConfig, StarlingError } from '@starling/core';
import type { DoctorExec } from './doctor';

export type ModelProfile = 'opencode' | 'deepseek' | 'local';

export const CONFIG_FILE = CONFIG_FILENAMES[0];

export interface InitOptions {
  cwd: string;
  force?: boolean;
  profile?: ModelProfile | 'auto';
  execFn: DoctorExec;
  env?: Record<string, string | undefined>;
}

export interface InitResult {
  path: string;
  profile: ModelProfile;
  overwrote: boolean;
}

const OPENCODE_FLASH = /opencode[-_][\w./-]*deepseek[\w./-]*flash/i;

/**
 * Write `starling.config.yaml`, auto-detecting the friendliest model profile.
 *
 * Order matters: an existing opencode-go login is the least setup (ARCHITECTURE L25), a direct
 * DeepSeek key is next, and a fully local profile is the always-works fallback. The generated file
 * is ordinary YAML parsed by `loadConfig`, so it can never drift from the zod schema's defaults for
 * the scalar fields.
 */
export async function initConfig(options: InitOptions): Promise<InitResult> {
  const target = resolve(options.cwd, CONFIG_FILE);
  const existed = existsSync(target);
  if (existed && options.force !== true) {
    throw new StarlingError(
      'INVALID_ARGUMENT',
      `${CONFIG_FILE} already exists at ${target} — rerun with --force to overwrite it`,
      { details: { path: target } },
    );
  }

  const profile =
    options.profile === undefined || options.profile === 'auto'
      ? await detectModelProfile(options)
      : options.profile;

  writeFileSync(target, renderConfigYaml(profile), 'utf8');
  return { path: target, profile, overwrote: existed };
}

/** Detect the model profile without ever throwing: an unavailable probe is just a fallback. */
export async function detectModelProfile(options: {
  execFn: DoctorExec;
  env?: Record<string, string | undefined>;
  cwd: string;
}): Promise<ModelProfile> {
  try {
    const result = await options.execFn(['opencode', 'models'], {
      cwd: options.cwd,
      timeoutMs: 15_000,
    });
    if (result.code === 0 && OPENCODE_FLASH.test(result.stdout)) return 'opencode';
  } catch {
    // No opencode on this machine — fall through to the API key / local checks.
  }

  const key = options.env?.DEEPSEEK_API_KEY;
  if (key !== undefined && key.length > 0) return 'deepseek';
  return 'local';
}

/**
 * Render the config template. Scalar values come from `defaultConfig`; only the profile-dependent
 * model refs and provider entries differ between profiles.
 */
export function renderConfigYaml(profile: ModelProfile): string {
  const base = defaultConfig;
  const flash = 'deepseek-v4.1-flash';
  const local = 'qwen3.6:35b-a3b';
  const models =
    profile === 'local'
      ? {
          planner: { provider: 'ollama', model: local },
          worker: { provider: 'ollama', model: local },
          resolver: { provider: 'ollama', model: local },
          auditor: { provider: 'ollama', model: local },
          summarizer: { provider: 'ollama', model: local },
          writer: { provider: 'ollama', model: local },
        }
      : {
          planner: { provider: profile === 'opencode' ? 'opencode-go' : 'deepseek', model: flash },
          worker: { provider: profile === 'opencode' ? 'opencode-go' : 'deepseek', model: flash },
          resolver: { provider: profile === 'opencode' ? 'opencode-go' : 'deepseek', model: flash },
          auditor: { provider: 'ollama', model: local },
          summarizer: { provider: 'ollama', model: local },
          writer: { provider: 'ollama', model: local },
        };

  const profileNote =
    profile === 'opencode'
      ? 'opencode-go (detected an opencode login with DeepSeek V4.1 Flash)'
      : profile === 'deepseek'
        ? 'deepseek (direct API via DEEPSEEK_API_KEY)'
        : 'local (Ollama only — no API keys needed; `--fully-open` is the default)';

  const providerLines: string[] = [];
  if (profile === 'opencode') {
    providerLines.push(
      '  # The opencode provider talks to your local `opencode serve`; no API key is read by Starling.',
      `  opencode-go: { baseUrl: http://127.0.0.1:${base.opencode.port} }`,
    );
  } else if (profile === 'deepseek') {
    providerLines.push(
      `  deepseek: { baseUrl: ${base.providers.deepseek?.baseUrl ?? 'https://api.deepseek.com/v1'}, apiKeyEnv: DEEPSEEK_API_KEY }`,
    );
  }
  providerLines.push('  ollama: { baseUrl: http://127.0.0.1:11434/v1 }');

  const role = (name: keyof typeof models): string => {
    const ref = models[name];
    const label = `  ${name}:`.padEnd(15);
    return `${label}{ provider: ${ref.provider}, model: ${ref.model} }`;
  };

  return `# Starling config — generated by \`starling init\`.
# Every field is optional; delete anything you are happy to inherit. See starling.config.example.yaml.
#
# Model profile: ${profileNote}

maxParallel: ${base.maxParallel}
maxAttempts: ${base.maxAttempts}
baseBranch: ${base.baseBranch}
integrationBranch: ${base.integrationBranch}          # starling/<runShort>/integration
worktreeRoot: ${base.worktreeRoot}
testCommand: ${base.testCommand}                    # detected by the repo map, overridable
lintCommand: ${base.lintCommand}

opencode:
  mode: ${base.opencode.mode}                     # spawn | attach
  port: ${base.opencode.port}
  url: null

models:
${role('planner')}
${role('worker')}   # the role opencode agents run as
${role('resolver')}
${role('auditor')}
${role('summarizer')}
${role('writer')}

providers:
${providerLines.join('\n')}

github: { enabled: ${base.github.enabled}, repo: null }
budget: { maxUsd: ${base.budget.maxUsd} }
server: { port: ${base.server.port} }

flock:
  enabled: ${base.flock.enabled}
  hubMaxSessions: ${base.flock.hubMaxSessions}          # LocalNode capacity on the hub
  mdns: ${base.flock.mdns}
  heartbeatMs: ${base.flock.heartbeatMs}
  offlineAfterMs: ${base.flock.offlineAfterMs}

perch:                       # used by \`starling perch\`
  port: ${base.perch.port}
  maxSessions: ${base.perch.maxSessions}
  name: ${base.perch.name}                 # hostname
  cacheDir: ${base.perch.cacheDir}
  lendModels: ${base.perch.lendModels}           # expose local Ollama models to the hub
`;
}
